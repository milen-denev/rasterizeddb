//! Collations: which text comparisons ignore case, or case and accents.
//!
//! The engine compares text by its bytes (PostgreSQL's `C`), and a
//! deterministic collation named on a column (`COLLATE "en_US"`) changes
//! nothing here, as before. A *nondeterministic* collation — PostgreSQL's ICU
//! `und-u-ks-level2` (case-insensitive) or `…-ks-level1` (case- and
//! accent-insensitive), MySQL's and SQL Server's defaults, `citext` — makes
//! `'Bob' = 'bob'` true, and that has to hold for every comparison the
//! column takes part in: `WHERE`, joins, `ORDER BY`, `GROUP BY`, `DISTINCT`,
//! unique keys and indexes. A comparison that answered bytewise would be a
//! different answer, silently.
//!
//! # The key column
//!
//! Such a column carries a hidden companion, `__ci_<column>` (or
//! `__cia_<column>` for accents too), holding its [`key`]: two values are
//! equal under the collation exactly when their keys are equal bytes, and
//! the collation orders them as their keys' bytes. The companion is a stored
//! generated column (`__rdb_ci_key(column)`), so every write path that
//! computes generated columns keeps it current, and everything the engine
//! does with plain bytes — indexes, unique keys, zone maps, filters, top-N —
//! works on it as it is. Comparisons read the companion instead of the
//! column (`collate_rewrite`); the column itself keeps the value as written,
//! which is what a query returns.
//!
//! The companion is the record of the collation: a column is
//! case-insensitive exactly when its companion exists ([`of`]), so the
//! schema's format is unchanged and an older build reads the table as it
//! always would have (with one more column it does not hide).
//!
//! # What the key is
//!
//! Unicode canonical decomposition (so `é` and `e` + U+0301 meet), lowercase
//! (full mappings: `İ` to `i̇`), and for the accent-insensitive strength every
//! combining mark dropped. Not ICU's: `ß` stays apart from `ss`, which ICU's
//! secondary strength would call equal, and the order is the keys' bytes
//! (the engine's `C` order of the folded text), not the Unicode Collation
//! Algorithm's.

use unicode_normalization::UnicodeNormalization;

use crate::core::row::schema::SchemaField;

/// How strongly a collation tells text apart.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum Strength {
    /// By the bytes: `C`, `POSIX`, `default`, every deterministic collation.
    Binary,
    /// Case does not count (`und-u-ks-level2`, `citext`, `…_CI_AS`).
    CaseInsensitive,
    /// Neither case nor accents count (`und-u-ks-level1`, `…_ai_ci`, `…_CI_AI`).
    CaseAccentInsensitive,
}

/// The companion prefix of a case-insensitive column.
pub const CI_PREFIX: &str = "__ci_";
/// The companion prefix of a case- and accent-insensitive column.
pub const CIA_PREFIX: &str = "__cia_";

/// The engine's own nondeterministic collations, listed in `pg_collation`.
pub const CI_NAME: &str = "rdb_ci";
pub const CIA_NAME: &str = "rdb_ci_ai";

/// The function a companion is generated by.
pub const CI_FUNCTION: &str = "__rdb_ci_key";
pub const CIA_FUNCTION: &str = "__rdb_ci_ai_key";

impl Strength {
    pub fn is_binary(self) -> bool {
        self == Strength::Binary
    }

    fn prefix(self) -> Option<&'static str> {
        match self {
            Strength::Binary => None,
            Strength::CaseInsensitive => Some(CI_PREFIX),
            Strength::CaseAccentInsensitive => Some(CIA_PREFIX),
        }
    }

    /// The name `pg_collation` and `information_schema` give it.
    pub fn name(self) -> &'static str {
        match self {
            Strength::Binary => "default",
            Strength::CaseInsensitive => CI_NAME,
            Strength::CaseAccentInsensitive => CIA_NAME,
        }
    }

    /// The function computing its key, by name.
    pub fn function(self) -> Option<&'static str> {
        match self {
            Strength::Binary => None,
            Strength::CaseInsensitive => Some(CI_FUNCTION),
            Strength::CaseAccentInsensitive => Some(CIA_FUNCTION),
        }
    }
}

/// The key of `text` under `strength`: equal keys are equal text, and the
/// keys' bytes are the order.
pub fn key(text: &str, strength: Strength) -> String {
    match strength {
        Strength::Binary => text.to_string(),
        Strength::CaseInsensitive => text.nfd().collect::<String>().to_lowercase().nfc().collect(),
        Strength::CaseAccentInsensitive => text
            .nfd()
            .collect::<String>()
            .to_lowercase()
            .nfd()
            .filter(|c| !unicode_normalization::char::is_combining_mark(*c))
            .collect(),
    }
}

/// The collation a name means, as `COLLATE <name>` and a column type
/// (`citext`) write it. `Err` for a name that is no collation (PostgreSQL's
/// 42704).
///
/// Every deterministic collation PostgreSQL knows by default orders text
/// its own way and compares it by its bytes; here every one of them is the
/// engine's bytes, as it was before collations were read at all.
pub fn resolve(name: &str) -> Result<Strength, String> {
    let n = name.trim().trim_matches('"');
    let lower = n.to_ascii_lowercase();
    match lower.as_str() {
        "c" | "posix" | "default" | "ucs_basic" | "pg_c_utf8" | "unicode" => return Ok(Strength::Binary),
        CI_NAME | "case_insensitive" | "und-u-ks-level2" | "und-x-icu-ks-level2" => {
            return Ok(Strength::CaseInsensitive);
        }
        CIA_NAME | "ignore_accents" | "und-u-ks-level1" | "und-x-icu-ks-level1" => {
            return Ok(Strength::CaseAccentInsensitive);
        }
        _ => {}
    }
    // libc and ICU locales (`en_US`, `en_US.utf8`, `de-DE-x-icu`, `und-x-icu`):
    // deterministic.
    let locale = lower.split(['.', '@']).next().unwrap_or("");
    let looks_like_locale = !locale.is_empty()
        && locale.chars().all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '-')
        && (lower.ends_with("-x-icu") || locale.len() <= 3 || locale.chars().nth(2).is_some_and(|c| c == '_' || c == '-'));
    if looks_like_locale {
        return Ok(Strength::Binary);
    }
    Err(format!("collation \"{n}\" for encoding \"UTF8\" does not exist"))
}

/// The companion of `column` under `strength`.
pub fn companion_name(column: &str, strength: Strength) -> Option<String> {
    strength.prefix().map(|p| format!("{p}{column}"))
}

/// Whether `name` is a collation companion.
pub fn is_companion(name: &str) -> bool {
    starts_with_ignore_case(name, CI_PREFIX) || starts_with_ignore_case(name, CIA_PREFIX)
}

fn starts_with_ignore_case(name: &str, prefix: &str) -> bool {
    name.len() >= prefix.len() && name.as_bytes()[..prefix.len()].eq_ignore_ascii_case(prefix.as_bytes())
}

/// The column a companion belongs to, and its strength.
pub fn companion_of(name: &str) -> Option<(&str, Strength)> {
    if starts_with_ignore_case(name, CIA_PREFIX) {
        Some((&name[CIA_PREFIX.len()..], Strength::CaseAccentInsensitive))
    } else if starts_with_ignore_case(name, CI_PREFIX) {
        Some((&name[CI_PREFIX.len()..], Strength::CaseInsensitive))
    } else {
        None
    }
}

/// The live companion of `column` in `fields`, if it has one.
pub fn companion<'a>(column: &str, fields: &'a [SchemaField]) -> Option<(&'a SchemaField, Strength)> {
    fields.iter().filter(|f| !f.is_deleted).find_map(|f| match companion_of(&f.name) {
        Some((base, strength)) if base.eq_ignore_ascii_case(column) => Some((f, strength)),
        _ => None,
    })
}

/// The collation of `column`.
pub fn of(column: &str, fields: &[SchemaField]) -> Strength {
    companion(column, fields).map(|(_, s)| s).unwrap_or(Strength::Binary)
}

/// Whether any live column of `fields` has a nondeterministic collation.
pub fn any(fields: &[SchemaField]) -> bool {
    fields.iter().any(|f| !f.is_deleted && is_companion(&f.name))
}

/// The generation expression of `column`'s companion.
pub fn companion_expression(column: &str, strength: Strength) -> Option<String> {
    strength.function().map(|f| format!("{f}({})", ident(column)))
}

/// `name` as SQL: bare only when folding cannot change it.
pub fn ident(name: &str) -> String {
    let bare = name.bytes().next().is_some_and(|b| b.is_ascii_lowercase() || b == b'_')
        && name.bytes().all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'_');
    if bare { name.to_string() } else { format!("\"{}\"", name.replace('"', "\"\"")) }
}

