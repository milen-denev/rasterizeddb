/// A single-table `SELECT`'s sort keys under its columns' collations, or the
/// statement refused where a step would compare such a column by its bytes.
///
/// `ORDER BY name` sorts by the key and then the value (so the order of
/// values that compare equal is still one order); the scan fetches the
/// companion as it fetches any unselected sort key, and trims it before the
/// client sees the row. Grouping, `DISTINCT`, an aggregate that compares
/// (`min`, `max`, `… DISTINCT …`) and a window over such a column are
/// refused for now: each would put rows that compare equal apart.
pub fn plan_single(
    select_list: &str,
    fields: &[SchemaField],
    order_terms: Vec<crate::core::rql::order_by::SortTerm>,
    group_by: &[SchemaField],
    grouped: bool,
    distinct: bool,
) -> Result<Vec<crate::core::rql::order_by::SortTerm>, String> {
    if !any(fields) {
        return Ok(order_terms);
    }
    let refuse = |what: &str, column: &str| {
        Err(format!(
            "{what} over column \"{column}\", which has a case-insensitive collation, is not supported yet"
        ))
    };
    let ci = |name: &str| -> Option<String> {
        let bare = name.rsplit('.').next().unwrap_or(name).trim_matches('"');
        fields
            .iter()
            .find(|f| !f.is_deleted && f.name.eq_ignore_ascii_case(bare))
            .filter(|f| !of(&f.name, fields).is_binary())
            .map(|f| f.name.clone())
    };
    if let Some(f) = group_by.iter().find(|f| !of(&f.name, fields).is_binary()) {
        return refuse("GROUP BY", &f.name);
    }
    // `SELECT DISTINCT *` selects every column, such ones among them.
    if distinct && select_list.contains('*') {
        if let Some(f) = fields.iter().find(|f| !f.is_deleted && !is_companion(&f.name) && !of(&f.name, fields).is_binary()) {
            return refuse("SELECT DISTINCT", &f.name);
        }
    }
    // The select list's words, for what it does with such a column.
    let words = words_of_list(select_list);
    for (k, w) in words.iter().enumerate() {
        let Some(column) = ci(w) else { continue };
        if distinct {
            return refuse("SELECT DISTINCT", &column);
        }
        let before = |n: usize| k.checked_sub(n).and_then(|i| words.get(i)).map(|s| s.to_ascii_uppercase());
        if matches!(before(1).as_deref(), Some("MIN" | "MAX" | "DISTINCT" | "PARTITION" | "BY")) {
            return refuse("this aggregate or window", &column);
        }
    }
    if words.iter().any(|w| w.eq_ignore_ascii_case("OVER")) && words.iter().any(|w| ci(w).is_some()) {
        if let Some(c) = words.iter().find_map(|w| ci(w)) {
            return refuse("a window function in a statement reading", &c);
        }
    }
    let mut out = Vec::with_capacity(order_terms.len());
    for term in order_terms {
        let Some(column) = ci(&term.token) else {
            out.push(term);
            continue;
        };
        if grouped || distinct {
            return refuse("ORDER BY in a grouped or DISTINCT query", &column);
        }
        let (key, _) = companion(&column, fields).expect("a nondeterministic column has its companion");
        out.push(crate::core::rql::order_by::SortTerm {
            token: ident(&key.name),
            descending: term.descending,
            nulls_first: term.nulls_first,
        });
        out.push(term);
    }
    Ok(out)
}

/// The words of a select list (identifiers and keywords, quoted names
/// unquoted, string literals skipped), with the parenthesis structure gone.
fn words_of_list(text: &str) -> Vec<String> {
    let bytes = text.as_bytes();
    let mut out = Vec::new();
    let mut i = 0;
    while i < bytes.len() {
        let b = bytes[i];
        if b == b'\'' {
            i = crate::core::sql_scan::quoted_end(bytes, i, b'\'');
        } else if b == b'"' {
            let end = crate::core::sql_scan::quoted_end(bytes, i, b'"');
            out.push(text[i + 1..end.saturating_sub(1).max(i + 1)].replace("\"\"", "\""));
            i = end;
        } else if b.is_ascii_alphabetic() || b == b'_' || b >= 0x80 {
            let start = i;
            while i < bytes.len() && (bytes[i].is_ascii_alphanumeric() || bytes[i] == b'_' || bytes[i] >= 0x80 || bytes[i] == b'.') {
                i += 1;
            }
            out.push(text[start..i].to_string());
        } else {
            i += 1;
        }
    }
    out
}

/// Refuses a multi-table query that compares a column with a
/// nondeterministic collation (in a join condition, `WHERE`, `GROUP BY`,
/// `HAVING`, `ORDER BY`, or the select list's `DISTINCT`, `min`/`max` and
/// windows): the join planner reads the relations' columns under labels of
/// its own, where the key companions are not found, and would compare by
/// the bytes. Selecting such a column is fine. `relations` is each
/// relation's label and fields.
pub fn refuse_in_join(
    relations: &[(&str, &[SchemaField])],
    select_list: &str,
    compared: &[&str],
) -> Result<(), String> {
    if !relations.iter().any(|(_, f)| any(f)) {
        return Ok(());
    }
    let ci = |word: &str| -> Option<String> {
        let (qualifier, column) = match word.rsplit_once('.') {
            Some((q, c)) => (Some(q.trim_matches('"')), c.trim_matches('"')),
            None => (None, word.trim_matches('"')),
        };
        relations
            .iter()
            .filter(|(label, _)| qualifier.is_none_or(|q| q.eq_ignore_ascii_case(label)))
            .find_map(|(_, fields)| {
                fields
                    .iter()
                    .find(|f| !f.is_deleted && f.name.eq_ignore_ascii_case(column))
                    .filter(|f| !of(&f.name, fields).is_binary())
                    .map(|f| f.name.clone())
            })
    };
    let refuse = |column: String| {
        Err(format!(
            "a join comparing column \"{column}\", which has a case-insensitive collation, is not supported yet"
        ))
    };
    for text in compared {
        if let Some(c) = words_of_list(text).iter().find_map(|w| ci(w)) {
            return refuse(c);
        }
    }
    let words = words_of_list(select_list);
    let distinct = words.first().is_some_and(|w| w.eq_ignore_ascii_case("DISTINCT"));
    let window = words.iter().any(|w| w.eq_ignore_ascii_case("OVER"));
    for (k, w) in words.iter().enumerate() {
        let Some(c) = ci(w) else { continue };
        let before = k.checked_sub(1).map(|i| words[i].to_ascii_uppercase());
        if distinct || window || matches!(before.as_deref(), Some("MIN" | "MAX" | "DISTINCT" | "BY")) {
            return refuse(c);
        }
    }
    Ok(())
}

/// Refuses a set operation that compares rows (anything but `UNION ALL`)
/// when a branch selects a column with a nondeterministic collation: the
/// rows would be told apart by their bytes. `table_fields` looks a branch's
/// relation up.
pub fn refuse_in_set_op(
    branches: &[String],
    compares: bool,
    table_fields: &dyn Fn(&str) -> Option<Vec<SchemaField>>,
) -> Result<(), String> {
    if !compares {
        return Ok(());
    }
    for branch in branches {
        let upper = branch.to_ascii_uppercase();
        let Some(from) = crate::core::rql::join::find_keyword(&upper, "FROM", 0) else { continue };
        let select_list = branch[..from].trim_start().get("SELECT".len()..).unwrap_or("");
        let table = words_of_list(&branch[from + "FROM".len()..]).into_iter().next().unwrap_or_default();
        let table = table.rsplit('.').next().unwrap_or(&table).to_string();
        let Some(fields) = table_fields(&table) else { continue };
        if !any(&fields) {
            continue;
        }
        let star = select_list.contains('*');
        let selected = words_of_list(select_list).into_iter().find_map(|w| {
            let bare = w.rsplit('.').next().unwrap_or(&w).to_string();
            fields
                .iter()
                .find(|f| !f.is_deleted && f.name.eq_ignore_ascii_case(&bare) && !of(&f.name, &fields).is_binary())
                .map(|f| f.name.clone())
        });
        let column = selected.or_else(|| {
            star.then(|| {
                fields
                    .iter()
                    .find(|f| !f.is_deleted && !is_companion(&f.name) && !of(&f.name, &fields).is_binary())
                    .map(|f| f.name.clone())
            })
            .flatten()
        });
        if let Some(c) = column {
            return Err(format!(
                "UNION, INTERSECT or EXCEPT over column \"{c}\", which has a case-insensitive collation, is not supported yet (UNION ALL is)"
            ));
        }
    }
    Ok(())
}

/// Whether `sql` declares a nondeterministic collation anywhere: a
/// `COLLATE` naming one, or the type `citext`. `ALTER TABLE` cannot give a
/// column one yet and refuses such a statement rather than add or retype a
/// column that compares by its bytes.
pub fn declares_nondeterministic(sql: &str) -> bool {
    let words = words_of(sql);
    words.iter().enumerate().any(|(k, w)| {
        let name = unquote(w.rsplit('.').next().unwrap_or(w));
        name.eq_ignore_ascii_case("citext")
            || (k > 0
                && words[k - 1].eq_ignore_ascii_case("COLLATE")
                && resolve(w.rsplit('.').next().unwrap_or(w)).is_ok_and(|s| !s.is_binary()))
    })
}
