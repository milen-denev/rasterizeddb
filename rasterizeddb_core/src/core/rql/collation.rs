/// The collation each column of a `CREATE TABLE`'s body declares, as
/// written: `COLLATE <name>` after its type, or the type `citext`. Columns
/// that name no collation, or a deterministic one, are left out.
fn declared(sql: &str) -> Result<Vec<(String, Strength)>, String> {
    let bytes = sql.as_bytes();
    // The body: the first top-level parenthesis after `TABLE <name>`.
    let Some(open) = sql.find('(') else { return Ok(Vec::new()) };
    let mut depth = 0i32;
    let mut close = None;
    let mut i = open;
    while i < bytes.len() {
        match bytes[i] {
            b'\'' | b'"' => {
                i = crate::core::sql_scan::quoted_end(bytes, i, bytes[i]);
                continue;
            }
            b'(' => depth += 1,
            b')' => {
                depth -= 1;
                if depth == 0 {
                    close = Some(i);
                    break;
                }
            }
            _ => {}
        }
        i += 1;
    }
    let Some(close) = close else { return Ok(Vec::new()) };
    let mut out = Vec::new();
    for part in split_top_commas(&sql[open + 1..close]) {
        let words = words_of(part);
        let Some(first) = words.first() else { continue };
        let head = first.to_ascii_uppercase();
        if matches!(
            head.as_str(),
            "CONSTRAINT" | "PRIMARY" | "UNIQUE" | "FOREIGN" | "CHECK" | "EXCLUDE" | "LIKE"
        ) {
            continue;
        }
        let column = unquote(first);
        let mut strength: Option<Strength> = None;
        if let Some(ty) = words.get(1) {
            let ty = unquote(ty.rsplit('.').next().unwrap_or(ty));
            if ty.eq_ignore_ascii_case("citext") {
                strength = Some(Strength::CaseInsensitive);
            }
        }
        for (k, w) in words.iter().enumerate() {
            if w.eq_ignore_ascii_case("COLLATE") {
                let Some(name) = words.get(k + 1) else {
                    return Err("syntax error at end of input: COLLATE needs a collation".to_string());
                };
                // `pg_catalog."C"`: the schema is set aside.
                let name = name.rsplit('.').next().unwrap_or(name);
                strength = Some(resolve(name)?);
            }
        }
        if let Some(s) = strength.filter(|s| !s.is_binary()) {
            out.push((column, s));
        }
    }
    Ok(out)
}

fn unquote(word: &str) -> String {
    let w = word.trim();
    if w.len() >= 2 && w.starts_with('"') && w.ends_with('"') {
        w[1..w.len() - 1].replace("\"\"", "\"")
    } else {
        w.to_ascii_lowercase()
    }
}

/// `text` split on commas outside parentheses and quotes.
fn split_top_commas(text: &str) -> Vec<&str> {
    let bytes = text.as_bytes();
    let (mut parts, mut depth, mut start, mut i) = (Vec::new(), 0i32, 0usize, 0usize);
    while i < bytes.len() {
        match bytes[i] {
            b'\'' | b'"' => {
                i = crate::core::sql_scan::quoted_end(bytes, i, bytes[i]);
                continue;
            }
            b'(' => depth += 1,
            b')' => depth -= 1,
            b',' if depth == 0 => {
                parts.push(&text[start..i]);
                start = i + 1;
            }
            _ => {}
        }
        i += 1;
    }
    parts.push(&text[start..]);
    parts
}

/// The top-level words of a column definition: identifiers (quoted ones
/// whole, qualified ones joined), with what is inside parentheses or string
/// literals left out.
fn words_of(part: &str) -> Vec<String> {
    let bytes = part.as_bytes();
    let (mut out, mut i, mut depth) = (Vec::<String>::new(), 0usize, 0i32);
    let mut joining = false;
    while i < bytes.len() {
        let b = bytes[i];
        match b {
            b'(' => {
                depth += 1;
                i += 1;
            }
            b')' => {
                depth -= 1;
                i += 1;
            }
            b'\'' => i = crate::core::sql_scan::quoted_end(bytes, i, b'\''),
            b'"' => {
                let end = crate::core::sql_scan::quoted_end(bytes, i, b'"');
                if depth == 0 {
                    let w = &part[i..end];
                    match (joining, out.last_mut()) {
                        (true, Some(last)) => last.push_str(w),
                        _ => out.push(w.to_string()),
                    }
                    joining = false;
                }
                i = end;
            }
            b'.' if depth == 0 => {
                if let Some(last) = out.last_mut() {
                    last.push('.');
                    joining = true;
                }
                i += 1;
            }
            _ if b.is_ascii_alphanumeric() || b == b'_' || b >= 0x80 => {
                let start = i;
                while i < bytes.len() && (bytes[i].is_ascii_alphanumeric() || bytes[i] == b'_' || bytes[i] >= 0x80 || bytes[i] == b'$') {
                    i += 1;
                }
                if depth == 0 {
                    let w = &part[start..i];
                    match (joining, out.last_mut()) {
                        (true, Some(last)) => last.push_str(w),
                        _ => out.push(w.to_string()),
                    }
                    joining = false;
                }
            }
            _ => i += 1,
        }
    }
    out
}

/// Gives each column of `ct` that declares a nondeterministic collation its
/// key companion (see the module docs): the companion column, its NULL flag
/// when the column is nullable, its generation expression, and the unique
/// keys over the column moved onto it, so uniqueness is the collation's.
///
/// What cannot yet honour a collation is refused rather than compared by
/// the bytes: such a column in a foreign key, in a `CHECK`, as a JSON
/// column, on a partitioned table, or on a type other than text.
pub fn apply_to_create(
    sql: &str,
    ct: &mut crate::core::rql::lexer_ct::CreateTable,
    partitioned: bool,
) -> Result<(), String> {
    use crate::core::db_type::DbType;
    use crate::core::rql::{generated::GeneratedColumn, lexer_ct::CreateColumnData, nullable, unique_key};
    let declared = declared(sql)?;
    if declared.is_empty() {
        return Ok(());
    }
    let unsupported = |what: &str| -> Result<(), String> {
        Err(format!("{what} is not supported with a case-insensitive collation yet"))
    };
    if partitioned {
        return unsupported("a partitioned table");
    }
    for (column, strength) in declared {
        let Some(declared_column) = ct.columns.iter().find(|c| c.name.eq_ignore_ascii_case(&column)) else {
            continue;
        };
        let name = declared_column.name.clone();
        if declared_column.data_type != DbType::STRING || ct.json_columns.iter().any(|j| j.column.eq_ignore_ascii_case(&name)) {
            return Err(format!("collations are not supported by the type of column \"{name}\""));
        }
        if ct.foreign_keys.iter().any(|fk| fk.column.eq_ignore_ascii_case(&name)) {
            return unsupported(&format!("a foreign key on column \"{name}\""));
        }
        if ct.checks.iter().any(|c| mentions(&c.expression, &name)) {
            return unsupported(&format!("a CHECK reading column \"{name}\""));
        }
        let companion = companion_name(&name, strength).expect("nondeterministic");
        if companion.len() > 128 || nullable::flag_column_name(&companion).len() > 128 {
            return Err(format!("column name \"{name}\" is too long for a case-insensitive collation"));
        }
        let nullable = ct.columns.iter().any(|c| c.name == nullable::flag_column_name(&name));
        ct.columns.push(CreateColumnData { name: companion.clone(), data_type: DbType::STRING });
        if nullable {
            ct.columns.push(CreateColumnData {
                name: nullable::flag_column_name(&companion),
                data_type: nullable::FLAG_TYPE,
            });
        }
        ct.generated.push(GeneratedColumn {
            column: companion.clone(),
            expression: companion_expression(&name, strength).expect("nondeterministic"),
            is_deleted: false,
        });
        // Uniqueness under the collation: on the key, under the constraint's
        // own name.
        if let Some(at) = ct.unique_columns.iter().position(|c| c.eq_ignore_ascii_case(&name)) {
            ct.unique_columns.remove(at);
            ct.unique_keys.push(unique_key::UniqueKey {
                name: unique_key::implicit_key_name(&ct.table_name, &name),
                columns: vec![companion.clone()],
                is_deleted: false,
                predicate: None,
                compiled: Default::default(),
                from_index: false,
            });
        }
        for key in ct.unique_keys.iter_mut() {
            for c in key.columns.iter_mut() {
                if c.eq_ignore_ascii_case(&name) {
                    *c = companion.clone();
                }
            }
        }
        // A primary key stays on the column (rows are found by it); the
        // collation's uniqueness is a key on the companion beside it.
        if ct.primary_key.as_deref().is_some_and(|pk| pk.eq_ignore_ascii_case(&name)) {
            ct.unique_keys.push(unique_key::UniqueKey {
                name: unique_key::name_with_label(&format!("{}_{}", ct.table_name, name), "_ci_key"),
                columns: vec![companion.clone()],
                is_deleted: false,
                predicate: None,
                compiled: Default::default(),
                from_index: false,
            });
        }
    }
    Ok(())
}

/// Whether `expression` names `column` as a word outside quotes.
fn mentions(expression: &str, column: &str) -> bool {
    words_of(expression).iter().any(|w| unquote(w).eq_ignore_ascii_case(column) || w.eq_ignore_ascii_case(column))
}

