//! `GENERATED { ALWAYS | BY DEFAULT } AS IDENTITY`, as PostgreSQL has it.
//!
//! The clause used to be accepted and ignored: the column was created with no
//! default, so `INSERT … RETURNING id` handed back NULL with no error, and
//! with a `PRIMARY KEY` every insert failed NOT NULL. `BY DEFAULT` was refused
//! by the DEFAULT reader. Django, EF Core and Rails all declare keys this way.

use rasterizeddb_compat::TestServer;
use sqlx::{AssertSqlSafe, Executor, Row};

fn code(e: &sqlx::Error) -> String {
    e.as_database_error().and_then(|d| d.code()).map(|c| c.to_string()).unwrap_or_else(|| e.to_string())
}

async fn ids(pool: &sqlx::PgPool, sql: &str) -> Vec<i64> {
    sqlx::query(AssertSqlSafe(sql))
        .fetch_all(pool)
        .await
        .unwrap_or_else(|e| panic!("{sql}: {e}"))
        .iter()
        .map(|r| r.get::<i64, _>(0))
        .collect()
}

async fn refused(pool: &sqlx::PgPool, sql: &str) -> String {
    let e = pool.execute(AssertSqlSafe(sql)).await.expect_err(sql);
    code(&e)
}

#[tokio::test(flavor = "multi_thread")]
async fn identity_columns_number_rows_and_guard_always() {
    let root = std::env::temp_dir().join(format!("identity_columns_{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&root);
    let root_text = root.to_string_lossy().into_owned();
    let mut server = TestServer::start_file_backed(&root_text).await.expect("server");
    let pool = server.connect_sqlx().await.expect("connect");
    pool.execute(
        "CREATE TABLE a (id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY, v TEXT); \
         CREATE TABLE d (id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, v TEXT); \
         CREATE TABLE o (id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1 CACHE 20 NO CYCLE), v TEXT)",
    )
    .await
    .expect("create");

    // Left out, the column is numbered, one row after another.
    assert_eq!(ids(&pool, "INSERT INTO a (v) VALUES ('x'), ('y') RETURNING id").await, [1, 2]);
    assert_eq!(ids(&pool, "INSERT INTO a (id, v) VALUES (DEFAULT, 'z') RETURNING id").await, [3]);
    let one: i32 = sqlx::query("INSERT INTO d (v) VALUES ('x') RETURNING id").fetch_one(&pool).await.expect("d").get(0);
    assert_eq!(one, 1);
    assert_eq!(ids(&pool, "INSERT INTO o (v) VALUES ('x') RETURNING id").await, [1]);

    // ALWAYS refuses a value, in every insert shape, and in an UPDATE.
    for sql in [
        "INSERT INTO a (id, v) VALUES (10, 'w')",
        "INSERT INTO a (v, id) VALUES ('w', 10), ('u', 11)",
        "INSERT INTO a VALUES (10, 'w')",
        "UPDATE a SET id = 10 WHERE v = 'x'",
    ] {
        assert_eq!(refused(&pool, sql).await, "428C9", "{sql}");
    }
    // ... unless the statement overrides it.
    assert_eq!(
        ids(&pool, "INSERT INTO a (id, v) OVERRIDING SYSTEM VALUE VALUES (10, 'w') RETURNING id").await,
        [10]
    );
    // OVERRIDING USER VALUE ignores the value written.
    let user = ids(&pool, "INSERT INTO a (id, v) OVERRIDING USER VALUE VALUES (500, 'u') RETURNING id").await;
    assert_eq!(user.len(), 1);
    assert_ne!(user[0], 500, "OVERRIDING USER VALUE took the value written");

    // The same clauses on INSERT … SELECT, with and without a column list.
    pool.execute("CREATE TABLE src (a BIGINT, b TEXT); INSERT INTO src VALUES (50, 'p'), (51, 'q')")
        .await
        .expect("src");
    assert_eq!(refused(&pool, "INSERT INTO a (id, v) SELECT a, b FROM src").await, "428C9");
    assert_eq!(
        ids(&pool, "INSERT INTO a (id, v) OVERRIDING SYSTEM VALUE SELECT a, b FROM src RETURNING id").await,
        [50, 51]
    );
    let from_select = ids(&pool, "INSERT INTO a OVERRIDING USER VALUE SELECT a, b FROM src RETURNING id").await;
    assert!(from_select.iter().all(|id| *id != 50 && *id != 51), "{from_select:?}");
    pool.execute("DELETE FROM a WHERE id IN (50, 51)").await.expect("tidy");
    // SET id = DEFAULT gets past the ALWAYS check; it then needs nextval as
    // an expression, which a SERIAL's DEFAULT needs too, and is refused by
    // name (0A000) until sequences are first-class.
    assert_eq!(refused(&pool, "UPDATE a SET id = DEFAULT WHERE v = 'x'").await, "0A000");
    pool.execute("DELETE FROM a WHERE v IN ('p', 'q')").await.expect("tidy");

    // BY DEFAULT takes a value as written, as SERIAL does.
    let ten: i32 = sqlx::query("INSERT INTO d (id, v) VALUES (10, 'w') RETURNING id")
        .fetch_one(&pool)
        .await
        .expect("explicit")
        .get(0);
    assert_eq!(ten, 10);
    pool.execute("UPDATE d SET id = 20 WHERE id = 10").await.expect("update by default");

    // Declarations PostgreSQL refuses, and the options this engine cannot
    // honour, are refused rather than ignored.
    for (sql, expected) in [
        ("CREATE TABLE bad1 (id TEXT GENERATED ALWAYS AS IDENTITY)", "22023"),
        ("CREATE TABLE bad2 (id INT DEFAULT 5 GENERATED ALWAYS AS IDENTITY)", "42601"),
        ("CREATE TABLE bad3 (id INT GENERATED ALWAYS AS IDENTITY (START WITH 100))", "0A000"),
        ("CREATE TABLE bad4 (id INT GENERATED ALWAYS AS IDENTITY (INCREMENT BY 5))", "0A000"),
        ("CREATE TABLE bad5 (id SERIAL GENERATED BY DEFAULT AS IDENTITY)", "42601"),
        ("ALTER TABLE d ADD COLUMN k INT GENERATED BY DEFAULT AS IDENTITY", "0A000"),
        ("ALTER TABLE a ALTER COLUMN id SET DEFAULT 5", "42601"),
        ("ALTER TABLE a ALTER COLUMN id DROP DEFAULT", "42601"),
        ("INSERT INTO a (id, v) OVERRIDING FOO VALUE VALUES (1, 'x')", "42601"),
    ] {
        assert_eq!(refused(&pool, sql).await, expected, "{sql}");
    }

    // After a restart the column is still an identity column, still ALWAYS,
    // and keeps counting above its rows.
    drop(pool);
    drop(server);
    server = TestServer::start_file_backed(&root_text).await.expect("restart");
    let pool = server.connect_sqlx().await.expect("reconnect");
    assert_eq!(refused(&pool, "INSERT INTO a (id, v) VALUES (99, 'r')").await, "428C9");
    let next = ids(&pool, "INSERT INTO a (v) VALUES ('r') RETURNING id").await;
    assert!(next[0] > 10.max(user[0]), "{next:?} after {user:?}");
    let n: i64 = sqlx::query("SELECT count(*) FROM a").fetch_one(&pool).await.expect("count").get(0);
    assert_eq!(n, 6);
    drop(pool);
    drop(server);
    let _ = std::fs::remove_dir_all(&root);
}

/// `ADD COLUMN … SERIAL` used to add a plain column: every row, old and new,
/// read NULL. Refused until an added column can be numbered.
#[tokio::test(flavor = "multi_thread")]
async fn an_added_serial_column_is_refused_not_left_null() {
    let server = TestServer::start().await.expect("server");
    let pool = server.connect_sqlx().await.expect("connect");
    pool.execute("CREATE TABLE s (v TEXT); INSERT INTO s VALUES ('a'), ('b')").await.expect("setup");
    for sql in ["ALTER TABLE s ADD COLUMN id SERIAL", "ALTER TABLE s ADD COLUMN id bigserial PRIMARY KEY"] {
        assert_eq!(refused(&pool, sql).await, "0A000", "{sql}");
    }
    let n: i64 = sqlx::query("SELECT count(*) FROM information_schema.columns WHERE table_name = 's'")
        .fetch_one(&pool)
        .await
        .expect("columns")
        .get(0);
    assert_eq!(n, 1, "the refused column was added anyway");
}
